#!/usr/bin/env bash
# setup-repo-scoping.sh — generate .ignore + .cursorignore for any repo.
#
# Auto-detects single-repo vs monorepo and writes appropriate scoping files
# so AI tools (OpenCode, Cursor, ripgrep, fd, ag) don't scan unnecessary files.
#
# Usage:
#   bash scripts/setup-repo-scoping.sh                    # current dir
#   bash scripts/setup-repo-scoping.sh /path/to/repo     # target dir
#   bash scripts/setup-repo-scoping.sh --monorepo         # force monorepo mode
#   bash scripts/setup-repo-scoping.sh --single          # force single-repo mode
set -euo pipefail

TARGET="."
FORCE_MONO=0
FORCE_SINGLE=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --monorepo) FORCE_MONO=1; shift ;;
    --single) FORCE_SINGLE=1; shift ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) TARGET="$1"; shift ;;
  esac
done

TARGET="$(cd "$TARGET" && pwd)"
BASENAME="$(basename "$TARGET")"

# ── Detect repo type ────────────────────────────────────────────────────────
# Monorepo = has 2+ subdirectories that each look like a project
# (each has package.json, composer.json, pyproject.toml, requirements.txt, or .git)

detect_monorepo() {
  local count=0
  for d in "$TARGET"/*/; do
    [[ -f "$d/package.json" ]] && count=$((count+1)) && continue
    [[ -f "$d/composer.json" ]] && count=$((count+1)) && continue
    [[ -f "$d/pyproject.toml" ]] && count=$((count+1)) && continue
    [[ -f "$d/requirements.txt" ]] && count=$((count+1)) && continue
    [[ -d "$d/.git" ]] && count=$((count+1)) && continue
  done
  [[ $count -ge 2 ]]
}

if [[ $FORCE_MONO -eq 1 ]]; then
  IS_MONO=true
elif [[ $FORCE_SINGLE -eq 1 ]]; then
  IS_MONO=false
else
  if detect_monorepo; then IS_MONO=true; else IS_MONO=false; fi
fi

# ── Common patterns ─────────────────────────────────────────────────────────
COMMON_PATTERNS='node_modules/
vendor/
dist/
build/
coverage/
.next/
.turbo/
.cache/
.ruff_cache/
.mypy_cache/
.pytest_cache/
__pycache__/
venv/
.venv/
env/
*.pyc
*.log
.git/
.DS_Store'

# ── Write ignore files ──────────────────────────────────────────────────────
write_ignore() {
  local file="$1"
  local extra="$2"
  {
    echo "# Auto-generated by setup-repo-scoping.sh — prevents tools from scanning unnecessary files."
    echo "# Respected by: $( [[ "$file" == *.ignore ]] && echo 'ripgrep, fd, ag, Sourcegraph' || echo 'Cursor indexer + watcher' )"
    echo ""
    echo "$COMMON_PATTERNS"
    [[ -n "$extra" ]] && echo "" && echo "$extra"
  } > "$file"
}

echo "==> Repo scoping setup"
echo "    Target: $TARGET"
echo "    Type:   $([[ $IS_MONO == true ]] && echo 'monorepo' || echo 'single-repo')"
echo ""

if [[ $IS_MONO == true ]]; then
  # Monorepo: write root ignores + per-subproject ignores
  echo "--- Root ignore files ---"
  SUBDIRS=""
  for d in "$TARGET"/*/; do
    [[ -d "$d" ]] || continue
    # Skip hidden dirs and common non-project dirs
    base="$(basename "$d")"
    [[ "$base" == .* ]] && continue
    [[ "$base" == "node_modules" || "$base" == "vendor" || "$base" == "dist" ]] && continue
    SUBDIRS="$SUBDIRS $base"
  done

  ROOT_EXTRA="# Heavy subproject subtrees — open directly if needed
$SUBDIRS"

  write_ignore "$TARGET/.ignore" "$ROOT_EXTRA"
  write_ignore "$TARGET/.cursorignore" "$ROOT_EXTRA"
  echo "    wrote: .ignore + .cursorignore (root)"

  echo ""
  echo "--- Per-subproject ignore files ---"
  for base in $SUBDIRS; do
    dir="$TARGET/$base"
    [[ -d "$dir" ]] || continue
    # Skip if already has both files
    if [[ -f "$dir/.ignore" && -f "$dir/.cursorignore" ]]; then
      echo "    skip (exists): $base/.ignore + .cursorignore"
      continue
    fi
    write_ignore "$dir/.ignore" ""
    write_ignore "$dir/.cursorignore" ""
    echo "    wrote: $base/.ignore + $base/.cursorignore"
  done
else
  # Single repo: just write root ignores
  echo "--- Ignore files ---"
  if [[ -f "$TARGET/.ignore" && -f "$TARGET/.cursorignore" ]]; then
    echo "    skip (both exist already)"
  else
    write_ignore "$TARGET/.ignore" ""
    write_ignore "$TARGET/.cursorignore" ""
    echo "    wrote: .ignore + .cursorignore"
  fi
fi

echo ""
echo "==> Done. Tools will now skip node_modules, vendor, venv, caches, and build artifacts."
echo "    Re-run after adding new subprojects to a monorepo."
